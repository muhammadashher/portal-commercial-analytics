"""Build outputs/Q4_2026_Target_Model.xlsx: a live Excel model with formulas.

Sheets: Read Me, Assumptions, Rep Targets (bottom-up Q4 2026 targets), Q3 Backtest,
P&L (last 12 months by vertical) and Pricing (cost-per-lead benchmark).
Blue = input, black = formula, green = link to another sheet, yellow fill = key lever.
"""
import json
import sys
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config as C  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analysis import bottom_up_expectation  # noqa: E402

FONT = "Arial"
BLUE = Font(name=FONT, color="0000FF")
BLACK = Font(name=FONT, color="000000")
GREEN = Font(name=FONT, color="008000")
BOLD = Font(name=FONT, bold=True)
TITLE = Font(name=FONT, bold=True, size=14, color="1F3A5F")
HEAD = Font(name=FONT, bold=True, color="FFFFFF")
HEAD_FILL = PatternFill("solid", fgColor="1F3A5F")
YELLOW = PatternFill("solid", fgColor="FFFF00")
THIN = Border(bottom=Side(style="thin", color="BFBFBF"))
AED = 'AED #,##0;(AED #,##0);"-"'
PCT = '0.0%;(0.0%);"-"'


def header(ws, row, labels, start_col=1):
    for i, lab in enumerate(labels):
        c = ws.cell(row=row, column=start_col + i, value=lab)
        c.font, c.fill = HEAD, HEAD_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    ws.row_dimensions[row].height = 32


def widths(ws, w):
    for i, x in enumerate(w, 1):
        ws.column_dimensions[get_column_letter(i)].width = x


def main():
    import sqlite3
    con = sqlite3.connect(C.DB_PATH)
    am = pd.read_sql("SELECT * FROM account_monthly", con)
    rm = pd.read_sql("SELECT * FROM rep_monthly", con)
    metrics = json.loads((C.OUT_DIR / "metrics.json").read_text())
    pnl = pd.read_csv(C.OUT_DIR / "pnl_by_vertical.csv")
    bt = pd.read_csv(C.OUT_DIR / "target_backtest_q3_2026.csv", index_col=0)
    price = pd.read_csv(C.OUT_DIR / "pricing_benchmark.csv")
    exp = bottom_up_expectation(rm, am, "2026-09").reset_index().rename(columns={"index": "rep_id"})
    q3 = rm[rm["month"].isin(["2026-07", "2026-08", "2026-09"])].groupby("vertical")["book_revenue"].sum()

    wb = Workbook()
    # ------------------------------------------------------------ Read Me
    ws = wb.active
    ws.title = "Read Me"
    rows = [("Q4 2026 Target & Commercial Model", TITLE), ("", None),
            ("Purpose: set fair Q4 2026 revenue targets for Property and Jobs inside-sales reps, "
             "track the P&L and benchmark pricing.", BLACK),
            ("Method: each rep's Sep-2026 book is projected forward with their trailing churn plus "
             "their new-business run-rate, then scaled so the vertical total equals the company goal.", BLACK),
            ("", None), ("How to use", BOLD),
            ("1. Change the growth goal (yellow cell) on the Assumptions sheet.", BLACK),
            ("2. Adjust any blue input on Rep Targets (e.g. a rep's churn) - all targets update.", BLACK),
            ("", None), ("Colour legend", BOLD),
            ("Blue text = input or data from the pipeline", BLUE),
            ("Black text = formula", BLACK), ("Green text = link to another sheet", GREEN),
            ("Yellow fill = key lever to change", BLACK), ("", None),
            ("Data: synthetic portal data generated by this project (Oct 2024 - Sep 2026). "
             "Competitor prices are illustrative.", BLACK)]
    for i, (text, font) in enumerate(rows, 1):
        c = ws.cell(row=i, column=1, value=text)
        if font:
            c.font = font
    ws["A14"].fill = YELLOW
    ws.column_dimensions["A"].width = 110

    # ------------------------------------------------------------ Assumptions
    wa = wb.create_sheet("Assumptions")
    wa["A1"], wa["A1"].font = "Assumptions", TITLE
    items = [
        (3, "Q4 2026 growth goal vs Q3 2026", C.Q4_2026_GROWTH_GOAL, PCT, BLUE, "Company goal (config.py)"),
        (4, "Property Q3 2026 actual revenue", round(q3["Property"], 0), AED, BLUE, "Pipeline: rep_monthly, Jul-Sep 2026"),
        (5, "Jobs Q3 2026 actual revenue", round(q3["Jobs"], 0), AED, BLUE, "Pipeline: rep_monthly, Jul-Sep 2026"),
        (7, "Property Q4 2026 goal", "=B4*(1+B3)", AED, BLACK, "Formula"),
        (8, "Jobs Q4 2026 goal", "=B5*(1+B3)", AED, BLACK, "Formula"),
        (10, "Payment fee rate", C.PAYMENT_FEE_RATE, PCT, BLUE, "Assumption (config.py)"),
        (11, "Tech allocation rate", C.TECH_ALLOCATION_RATE, PCT, BLUE, "Assumption (config.py)"),
        (13, "Average listing utilization (Property, Q3 2026)",
         round(am[(am.vertical == "Property") & (am.month >= "2026-07")]["utilization"].mean(), 3),
         "0.0%", BLUE, "Pipeline: account_monthly"),
        (14, "Leads per listing per month (Q3 2026)", round(metrics["leads_per_listing_q3"], 3),
         "0.00", BLUE, "Pipeline: account_monthly"),
    ]
    header(wa, 2, ["Assumption", "Value", "Source / note"])
    for r, label, val, fmt, font, note in items:
        wa.cell(row=r, column=1, value=label).font = BLACK
        c = wa.cell(row=r, column=2, value=val)
        c.number_format, c.font = fmt, font
        wa.cell(row=r, column=3, value=note).font = Font(name=FONT, italic=True, color="7F7F7F")
    wa["B3"].fill = YELLOW
    widths(wa, [48, 18, 42])

    # ------------------------------------------------------------ Rep Targets
    wr = wb.create_sheet("Rep Targets")
    wr["A1"], wr["A1"].font = "Q4 2026 Rep Targets (bottom-up capacity model)", TITLE
    cols = ["Rep", "Vertical", "Sep-26 book revenue", "Trailing monthly churn", "New-business run-rate / month",
            "Expected Oct", "Expected Nov", "Expected Dec", "Expected Q4", "Share of vertical",
            "Q4 target", "Target Oct", "Target Nov", "Target Dec"]
    header(wr, 3, cols)
    exp = exp.sort_values(["vertical", "rep_id"], ascending=[False, True])
    first = 4
    last = first + len(exp) - 1
    for i, r in enumerate(exp.itertuples(), first):
        wr.cell(row=i, column=1, value=r.rep_id).font = BLACK
        wr.cell(row=i, column=2, value=r.vertical).font = BLACK
        for col, val, fmt in [(3, round(r.base_book, 0), AED), (4, round(r.trailing_churn, 4), PCT),
                              (5, round(r.new_rate, 0), AED)]:
            c = wr.cell(row=i, column=col, value=val)
            c.number_format, c.font = fmt, BLUE
        f = {
            6: f"=C{i}*(1-D{i})+E{i}",
            7: f"=C{i}*(1-D{i})^2+E{i}*((1-D{i})+1)",
            8: f"=C{i}*(1-D{i})^3+E{i}*((1-D{i})^2+(1-D{i})+1)",
            9: f"=SUM(F{i}:H{i})",
            10: f"=IFERROR(I{i}/SUMIF($B${first}:$B${last},B{i},$I${first}:$I${last}),0)",
            11: f"=J{i}*IF(B{i}=\"Property\",Assumptions!$B$7,Assumptions!$B$8)",
            12: f"=IFERROR(K{i}*F{i}/I{i},0)",
            13: f"=IFERROR(K{i}*G{i}/I{i},0)",
            14: f"=IFERROR(K{i}*H{i}/I{i},0)",
        }
        for col, formula in f.items():
            c = wr.cell(row=i, column=col, value=formula)
            c.number_format = PCT if col == 10 else AED
            c.font = GREEN if col == 11 else BLACK
            c.border = THIN
    tot = last + 2
    for j, v in enumerate(["Property", "Jobs"]):
        r = tot + j
        wr.cell(row=r, column=1, value=f"Total {v}").font = BOLD
        wr.cell(row=r, column=2, value=v).font = BOLD
        for col in [3, 6, 7, 8, 9, 11, 12, 13, 14]:
            L = get_column_letter(col)
            c = wr.cell(row=r, column=col,
                        value=f"=SUMIF($B${first}:$B${last},$B{r},{L}${first}:{L}${last})")
            c.number_format, c.font = AED, BOLD
    chk = tot + 3
    wr.cell(row=chk, column=1, value="Check: targets equal goal").font = BOLD
    wr.cell(row=chk, column=11,
            value=f"=IF(ABS(K{tot}-Assumptions!B7)+ABS(K{tot + 1}-Assumptions!B8)<1,\"OK\",\"CHECK\")").font = BOLD
    wr.freeze_panes = "C4"
    widths(wr, [10, 11, 17, 13, 17, 15, 15, 15, 16, 12, 17, 15, 15, 15])

    # ------------------------------------------------------------ Q3 Backtest
    wbk = wb.create_sheet("Q3 Backtest")
    wbk["A1"], wbk["A1"].font = "Q3 2026 Backtest: legacy equal-split vs bottom-up targets", TITLE
    header(wbk, 3, ["Rep", "Vertical", "Actual Q3", "Legacy target", "Bottom-up target",
                    "Legacy attainment", "Bottom-up attainment"])
    bt = bt.sort_values(["vertical", "actual_q3"], ascending=[False, False])
    s = 4
    for i, (rep, r) in enumerate(bt.iterrows(), s):
        wbk.cell(row=i, column=1, value=rep)
        wbk.cell(row=i, column=2, value=r.vertical)
        for col, val in [(3, r.actual_q3), (4, r.legacy_target_q3), (5, r.bottom_up_target_q3)]:
            c = wbk.cell(row=i, column=col, value=round(val, 0))
            c.number_format, c.font = AED, BLUE
        for col, formula in [(6, f"=C{i}/D{i}"), (7, f"=C{i}/E{i}")]:
            c = wbk.cell(row=i, column=col, value=formula)
            c.number_format = PCT
    e = s + len(bt) - 1
    stats = [("Min attainment", "MIN"), ("Max attainment", "MAX"), ("Std deviation", "STDEV")]
    for j, (lab, fn) in enumerate(stats, e + 2):
        wbk.cell(row=j, column=1, value=lab).font = BOLD
        for col in (6, 7):
            L = get_column_letter(col)
            c = wbk.cell(row=j, column=col, value=f"={fn}({L}{s}:{L}{e})")
            c.number_format = PCT if fn != "STDEV" else "0.000"
    j = e + 5
    wbk.cell(row=j, column=1, value="Reps within +/-10%").font = BOLD
    for col in (6, 7):
        L = get_column_letter(col)
        c = wbk.cell(row=j, column=col,
                     value=f'=COUNTIFS({L}{s}:{L}{e},">=0.9",{L}{s}:{L}{e},"<=1.1")/COUNT({L}{s}:{L}{e})')
        c.number_format = PCT
    widths(wbk, [10, 11, 16, 16, 18, 18, 20])

    # ------------------------------------------------------------ P&L
    wp = wb.create_sheet("P&L")
    wp["A1"], wp["A1"].font = "Monthly P&L by vertical (last 12 months)", TITLE
    months = sorted(pnl["month"].unique())[-12:]
    row = 3
    for v in ["Property", "Jobs"]:
        d = pnl[(pnl.vertical == v) & (pnl.month.isin(months))].set_index("month").loc[months]
        header(wp, row, [f"{v} (AED)"] + months + ["Total"])
        r0 = row + 1
        lines = [("Net revenue", "revenue", True), ("Payment fees", None, False),
                 ("Tech allocation", None, False), ("Sales team cost", "sales_team_cost", True),
                 ("Commissions", "commissions", True), ("Marketing spend", "marketing_spend", True),
                 ("Contribution", None, False), ("Contribution margin", None, False)]
        for k, (label, col, is_input) in enumerate(lines):
            r = r0 + k
            wp.cell(row=r, column=1, value=label).font = BOLD if label.startswith("Contribution") else BLACK
            for m_i, m in enumerate(months, 2):
                L = get_column_letter(m_i)
                if is_input:
                    val, font = round(float(d.loc[m, col]), 0), BLUE
                elif label == "Payment fees":
                    val, font = f"={L}{r0}*Assumptions!$B$10", GREEN
                elif label == "Tech allocation":
                    val, font = f"={L}{r0}*Assumptions!$B$11", GREEN
                elif label == "Contribution":
                    val, font = f"={L}{r0}-SUM({L}{r0 + 1}:{L}{r0 + 5})", BOLD
                else:
                    val, font = f"=IFERROR({L}{r0 + 6}/{L}{r0},0)", BOLD
                c = wp.cell(row=r, column=m_i, value=val)
                c.font = font
                c.number_format = PCT if label == "Contribution margin" else AED
            tc = len(months) + 2
            TL = get_column_letter(tc)
            if label == "Contribution margin":
                val = f"=IFERROR({TL}{r0 + 6}/{TL}{r0},0)"
            else:
                val = f"=SUM(B{r}:{get_column_letter(tc - 1)}{r})"
            c = wp.cell(row=r, column=tc, value=val)
            c.font, c.number_format = BOLD, PCT if label == "Contribution margin" else AED
        row = r0 + len(lines) + 2
    widths(wp, [22] + [13] * 12 + [15])
    wp.freeze_panes = "B4"

    # ------------------------------------------------------------ Pricing
    wq = wb.create_sheet("Pricing")
    wq["A1"], wq["A1"].font = "Cost-per-lead benchmark, Q3 2026 (illustrative competitor data)", TITLE
    header(wq, 3, ["Portal", "Tier", "Monthly price", "Listing credits", "Lead index",
                   "Leads / month", "Cost per lead", "vs our portal"])
    price = price.sort_values(["tier", "portal"])
    s = 4
    e = s + len(price) - 1
    for i, r in enumerate(price.itertuples(), s):
        wq.cell(row=i, column=1, value=r.portal)
        wq.cell(row=i, column=2, value=r.tier)
        for col, val, fmt in [(3, r.monthly_price_aed, AED), (4, r.listing_credits, "0"), (5, r.lead_index, "0.00")]:
            c = wq.cell(row=i, column=col, value=val)
            c.number_format, c.font = fmt, BLUE
        c = wq.cell(row=i, column=6, value=f"=D{i}*Assumptions!$B$13*Assumptions!$B$14*E{i}")
        c.number_format, c.font = "#,##0", GREEN
        c = wq.cell(row=i, column=7, value=f"=IFERROR(C{i}/F{i},0)")
        c.number_format = "AED #,##0.00"
        c = wq.cell(row=i, column=8,
                    value=f'=IFERROR(G{i}/SUMIFS($G${s}:$G${e},$A${s}:$A${e},"Our Portal",$B${s}:$B${e},B{i})-1,0)')
        c.number_format = '+0%;-0%;0%'
    widths(wq, [16, 10, 15, 15, 12, 14, 15, 14])

    for sheet in wb.worksheets:
        for row_cells in sheet.iter_rows():
            for c in row_cells:
                if c.font and c.font.name != FONT:
                    c.font = Font(name=FONT, bold=c.font.bold, italic=c.font.italic,
                                  color=c.font.color, size=c.font.size)
    out = C.OUT_DIR / "Q4_2026_Target_Model.xlsx"
    wb.save(out)
    print(f"Excel model written to {out}")


if __name__ == "__main__":
    main()
